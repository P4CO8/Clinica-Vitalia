from contextlib import contextmanager
from dataclasses import dataclass
from uuid import UUID

import psycopg
from psycopg.rows import dict_row

from .repository import DuplicateDocumentError, Patient, PatientValidationError


class DatabaseUnavailable(RuntimeError):
    """El motor o el túnel no permite completar una operación."""


class ConfigurationError(RuntimeError):
    """La configuración local necesita completarse."""


class Database:
    def __init__(self, url):
        self.url = url

    @contextmanager
    def connect(self):
        try:
            with psycopg.connect(self.url, connect_timeout=5, row_factory=dict_row) as connection:
                yield connection
        except (psycopg.OperationalError, psycopg.InterfaceError) as error:
            raise DatabaseUnavailable("No se pudo conectar con la base de datos.") from error

    def verify_schema(self):
        try:
            with self.connect() as connection:
                rows = connection.execute("SELECT version FROM clinica.version_esquema").fetchall()
        except psycopg.Error as error:
            raise ConfigurationError("Instala el esquema SQL de Clínica Vitalia antes de iniciar.") from error
        if not {"1.0", "1.1", "1.2", "1.3", "1.4", "1.5", "1.6", "1.7", "1.8", "1.9"}.issubset({row["version"] for row in rows}):
            raise ConfigurationError("Aplica la actualización con python actualizar_sql.py.")


PATIENT_COLUMNS = """paciente_id, nombres, apellidos, tipo_documento,
    numero_documento, fecha_nacimiento, telefono, grupo_sanguineo, activo"""


def patient_from_row(row):
    return Patient(
        internal_id=row["paciente_id"],
        first_names=row["nombres"],
        last_names=row["apellidos"],
        document_type=row["tipo_documento"],
        document_number=row["numero_documento"],
        birth_date=row["fecha_nacimiento"].isoformat(),
        phone=row["telefono"],
        blood_type=row["grupo_sanguineo"],
        active=row["activo"],
    )


class PostgresPatientRepository:
    def __init__(self, database):
        self.database = database

    def list_all(self):
        with self.database.connect() as connection:
            rows = connection.execute(
                f"SELECT {PATIENT_COLUMNS} FROM clinica.pacientes ORDER BY creado_en, paciente_id"
            ).fetchall()
        return [patient_from_row(row) for row in rows]

    def add(self, first_names="", last_names="", document_type="", document_number="",
            birth_date="", phone="", blood_type="", name=None, document=None):
        from .validation import normalize_name, validate_patient_form

        if name is not None:
            first_names, last_names = name, ""
        if document is not None:
            document_number = document
        first_names = normalize_name(first_names)
        last_names = normalize_name(last_names)
        errors = validate_patient_form(
            first_names, last_names, document_type, document_number, birth_date, phone, blood_type
        )
        if errors:
            raise PatientValidationError(errors)
        try:
            with self.database.connect() as connection:
                row = connection.execute(
                    f"""INSERT INTO clinica.pacientes
                    (nombres, apellidos, tipo_documento, numero_documento,
                     fecha_nacimiento, telefono, grupo_sanguineo)
                    VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING {PATIENT_COLUMNS}""",
                    (first_names, last_names, document_type, document_number,
                     birth_date, phone, blood_type),
                ).fetchone()
        except psycopg.errors.UniqueViolation as error:
            if error.diag.constraint_name == "ix_pacientes_documento":
                raise DuplicateDocumentError from error
            raise
        except psycopg.errors.CheckViolation as error:
            field = {
                "ck_pacientes_nombres": "first_names",
                "ck_pacientes_apellidos": "last_names",
                "ck_pacientes_documento": "document_number",
                "ck_pacientes_telefono": "phone",
                "ck_pacientes_sangre": "blood_type",
            }.get(error.diag.constraint_name, "document_number")
            raise PatientValidationError({field: "Verifica este dato e intenta nuevamente."}) from error
        except psycopg.DatabaseError as error:
            if error.sqlstate == "P1002":
                raise PatientValidationError({"birth_date": "Esta fecha es incorrecta."}) from error
            raise
        return patient_from_row(row)

    def set_active(self, internal_id, active):
        try:
            UUID(internal_id.replace("PAC-", ""))
        except (ValueError, AttributeError):
            # IDs generated by the schema may be longer than a UUID after PAC-.
            if not isinstance(internal_id, str) or not internal_id.startswith("PAC-"):
                return None
        with self.database.connect() as connection:
            row = connection.execute(
                f"UPDATE clinica.pacientes SET activo=%s WHERE paciente_id=%s RETURNING {PATIENT_COLUMNS}",
                (active, internal_id),
            ).fetchone()
        return patient_from_row(row) if row else None

    def update(self, internal_id, **values):
        from .validation import normalize_name, validate_patient_form
        values["first_names"] = normalize_name(values["first_names"])
        values["last_names"] = normalize_name(values["last_names"])
        errors = validate_patient_form(**values)
        if errors:
            raise PatientValidationError(errors)
        try:
            with self.database.connect() as connection:
                row = connection.execute(
                    f"""UPDATE clinica.pacientes SET nombres=%s, apellidos=%s,
                    tipo_documento=%s, numero_documento=%s, fecha_nacimiento=%s,
                    telefono=%s, grupo_sanguineo=%s WHERE paciente_id=%s
                    RETURNING {PATIENT_COLUMNS}""",
                    (values["first_names"], values["last_names"], values["document_type"],
                     values["document_number"], values["birth_date"], values["phone"],
                     values["blood_type"], internal_id),
                ).fetchone()
        except psycopg.errors.UniqueViolation as error:
            raise DuplicateDocumentError from error
        return patient_from_row(row) if row else None


