class PostgresAdministrationRepository:
    def __init__(self, database):
        self.database = database

    def users(self):
        with self.database.connect() as connection:
            return connection.execute(
                """SELECT u.usuario_id, u.nombre_usuario, r.nombre AS rol, u.activo,
                u.nombres, u.apellidos, u.tipo_documento, u.numero_documento
                FROM clinica.usuarios u JOIN clinica.roles r USING (rol_id)
                ORDER BY u.nombre_usuario"""
            ).fetchall()

    def roles(self):
        with self.database.connect() as connection:
            return connection.execute("SELECT rol_id, nombre FROM clinica.roles ORDER BY nombre").fetchall()

    def available_doctor_users(self):
        with self.database.connect() as connection:
            return connection.execute(
                """SELECT u.usuario_id, u.nombre_usuario
                FROM clinica.usuarios u
                JOIN clinica.roles r ON r.rol_id = u.rol_id
                LEFT JOIN clinica.medicos m ON m.usuario_id = u.usuario_id
                WHERE r.nombre = 'MEDICO' AND u.activo AND m.usuario_id IS NULL
                ORDER BY u.nombre_usuario"""
            ).fetchall()

    def create_user(self, username, password_hash, role_id, personal_data):
        with self.database.connect() as connection:
            return connection.execute(
                """INSERT INTO clinica.usuarios(
                    nombre_usuario,password_hash,rol_id,nombres,apellidos,
                    tipo_documento,numero_documento,telefono,formacion_academica,
                    seguridad_social_salud_ocupacional,bioseguridad,
                    antecedentes,datos_financieros_tributarios
                ) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                RETURNING usuario_id""",
                (
                    username, password_hash, role_id,
                    personal_data["first_names"], personal_data["last_names"],
                    personal_data["document_type"], personal_data["document_number"],
                    personal_data["phone"], personal_data["training"],
                    personal_data["occupational"], personal_data["biosecurity"],
                    personal_data["backgrounds"], personal_data["financial"],
                ),
            ).fetchone()

    def set_user_active(self, user_id, active, actor_id):
        with self.database.connect() as connection:
            if not active:
                target = connection.execute(
                    """SELECT r.nombre AS rol, u.activo
                    FROM clinica.usuarios u JOIN clinica.roles r USING (rol_id)
                    WHERE u.usuario_id=%s FOR UPDATE""",
                    (user_id,),
                ).fetchone()
                if target is None:
                    return None
                if target["rol"] == "ADMINISTRADOR" and target["activo"]:
                    admins = connection.execute(
                        """SELECT count(*) AS total
                        FROM clinica.usuarios u JOIN clinica.roles r USING (rol_id)
                        WHERE r.nombre='ADMINISTRADOR' AND u.activo""",
                    ).fetchone()["total"]
                    if admins <= 1:
                        raise ValueError(
                            "No puedes desactivar al último administrador activo. "
                            "Registra y activa otro administrador primero."
                        )
            return connection.execute(
                "UPDATE clinica.usuarios SET activo=%s WHERE usuario_id=%s RETURNING usuario_id",
                (active, user_id),
            ).fetchone()

    def doctors(self):
        with self.database.connect() as connection:
            return connection.execute(
                """SELECT m.medico_id, m.nombre, m.registro_profesional,
                m.usuario_id, m.activo,
                COALESCE(string_agg(e.nombre, ', ' ORDER BY e.nombre), '') AS especialidades
                FROM clinica.medicos m
                LEFT JOIN clinica.medico_especialidad me ON me.medico_id=m.medico_id
                LEFT JOIN clinica.especialidades e ON e.especialidad_id=me.especialidad_id
                GROUP BY m.medico_id ORDER BY m.nombre"""
            ).fetchall()

    def specialties(self):
        with self.database.connect() as connection:
            return connection.execute(
                "SELECT especialidad_id, nombre, categoria FROM clinica.especialidades ORDER BY categoria, nombre"
            ).fetchall()

    def create_doctor(self, name, professional_id, user_id, specialty_ids):
        with self.database.connect() as connection:
            if not user_id:
                raise ValueError("Selecciona un usuario activo con rol MEDICO.")
            valid_user = connection.execute(
                """SELECT 1
                FROM clinica.usuarios u
                JOIN clinica.roles r ON r.rol_id = u.rol_id
                LEFT JOIN clinica.medicos m ON m.usuario_id = u.usuario_id
                WHERE u.usuario_id=%s AND r.nombre='MEDICO'
                  AND u.activo AND m.usuario_id IS NULL""",
                (user_id,),
            ).fetchone()
            if valid_user is None:
                raise ValueError("El usuario debe estar activo, tener rol MEDICO y no estar vinculado.")
            row = connection.execute(
                """INSERT INTO clinica.medicos(nombre,registro_profesional,usuario_id)
                VALUES (%s,%s,%s) RETURNING medico_id""",
                (name, professional_id, user_id or None),
            ).fetchone()
            for specialty_id in specialty_ids:
                connection.execute(
                    """INSERT INTO clinica.medico_especialidad(medico_id,especialidad_id)
                    VALUES (%s,%s)""",
                    (row["medico_id"], specialty_id),
                )
            return row

    def set_doctor_active(self, doctor_id, active):
        with self.database.connect() as connection:
            return connection.execute(
                "UPDATE clinica.medicos SET activo=%s WHERE medico_id=%s RETURNING medico_id",
                (active, doctor_id),
            ).fetchone()

    def create_specialty(self, name, category):
        with self.database.connect() as connection:
            return connection.execute(
                "INSERT INTO clinica.especialidades(nombre, categoria) VALUES (%s,%s) RETURNING especialidad_id",
                (name, category),
            ).fetchone()


@dataclass(frozen=True)
class ApplicationUser:
    user_id: str
    username: str
    password_hash: str
    role: str
    active: bool


class PostgresUserRepository:
    def __init__(self, database):
        self.database = database

    def _find(self, condition, value):
        with self.database.connect() as connection:
            row = connection.execute(
                f"""SELECT u.usuario_id, u.nombre_usuario, u.password_hash, u.activo, r.nombre AS rol
                FROM clinica.usuarios u JOIN clinica.roles r USING (rol_id)
                WHERE {condition}""",
                (value,),
            ).fetchone()
        if row is None:
            return None
        return ApplicationUser(
            str(row["usuario_id"]), row["nombre_usuario"], row["password_hash"], row["rol"], row["activo"]
        )

    def find_by_username(self, username):
        return self._find("lower(u.nombre_usuario) = lower(%s)", username)

    def find_by_id(self, user_id):
        try:
            identifier = UUID(user_id)
        except (ValueError, TypeError, AttributeError):
            return None
        return self._find("u.usuario_id = %s", identifier)
